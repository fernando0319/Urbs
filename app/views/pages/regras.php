<h1>Regras de participação</h1>
<p class="lead-sm">Regras públicas, aplicadas igualmente a todas as pessoas. As ações da moderação ficam registradas na página de <a href="<?= e(url('/transparencia')) ?>">transparência</a>.</p>

<h2>O que é bem-vindo</h2>
<ul>
  <li>Problemas e sugestões sobre espaços e serviços da cidade.</li>
  <li>Propostas de qualquer pessoa, técnicas ou artísticas.</li>
  <li>Críticas a ideias e projetos, feitas com respeito.</li>
</ul>

<h2>O que não é permitido</h2>
<ul>
  <li><strong>Propaganda político-partidária</strong>: pedidos de voto, promoção de candidatos, partidos ou mandatos. A plataforma não tem perfis partidários.</li>
  <li><strong>Exposição de pessoas</strong>: fotos com rostos identificáveis, placas de veículos, endereços residenciais ou outros dados pessoais. Fotos assim são recusadas ou removidas.</li>
  <li><strong>Ataques pessoais</strong>, discurso de ódio, discriminação, ameaças e assédio.</li>
  <li><strong>Plágio</strong>: enviar como seu o trabalho de outra pessoa sem autorização e crédito.</li>
  <li><strong>Spam</strong>, propaganda comercial e conteúdo repetido.</li>
  <li><strong>Manipulação</strong>: criar várias contas para apoiar ou votar, ou combinar votos em troca de vantagens.</li>
  <li>Informações sabidamente falsas.</li>
</ul>

<h2>Como a moderação funciona</h2>
<ul>
  <li>As primeiras publicações de cada conta passam por uma revisão rápida antes de aparecer.</li>
  <li>Qualquer pessoa pode denunciar um conteúdo. As denúncias são analisadas pela moderação.</li>
  <li>Quando um conteúdo é recusado, o autor recebe o motivo por e-mail.</li>
  <li>Violações graves ou repetidas levam ao bloqueio da conta.</li>
  <li>A moderação não remove conteúdo por discordar de uma ideia, só por violar estas regras.</li>
</ul>

<h2>Apoios e preferências</h2>
<p>Cada conta pode apoiar uma ocorrência uma vez e indicar uma proposta preferida por lugar. Os resultados mostram a opinião de quem participou, não de toda a população, e <strong>não têm caráter vinculante</strong>. Apoios de moradores verificados aparecem separados para dar mais contexto.</p>
